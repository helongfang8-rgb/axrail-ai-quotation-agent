"""Deploy the reviewed CodeZip artifact to AgentCore Runtime in Singapore.

Run in an authenticated AWS environment after provision_aws.py. The ZIP is
generated by build_runtime_zip.py and contains no sample customer files.
"""
import argparse
import json
import os
import time
from pathlib import Path

import boto3
from botocore.exceptions import ClientError

ROOT = Path(__file__).resolve().parents[1]
REGION = os.environ.get("AWS_REGION", "ap-southeast-1")
if REGION.startswith("cn-"):
    raise SystemExit("A global AWS region is required")


def config_from_file(path):
    return dict(line.strip().split("=", 1) for line in path.read_text().splitlines() if "=" in line)


def ensure_bucket(s3, name):
    try:
        s3.head_bucket(Bucket=name)
    except ClientError as error:
        if error.response["Error"]["Code"] not in ("404", "NoSuchBucket"):
            raise
        s3.create_bucket(Bucket=name, CreateBucketConfiguration={"LocationConstraint": REGION})
    s3.put_public_access_block(Bucket=name, PublicAccessBlockConfiguration={
        "BlockPublicAcls": True, "IgnorePublicAcls": True,
        "BlockPublicPolicy": True, "RestrictPublicBuckets": True})
    s3.put_bucket_encryption(Bucket=name, ServerSideEncryptionConfiguration={
        "Rules": [{"ApplyServerSideEncryptionByDefault": {"SSEAlgorithm": "AES256"}}]})


def ensure_role(iam, name, account, bucket, key, gateway_id, memory_id):
    trust = {"Version": "2012-10-17", "Statement": [{
        "Effect": "Allow", "Principal": {"Service": "bedrock-agentcore.amazonaws.com"},
        "Action": "sts:AssumeRole", "Condition": {
            "StringEquals": {"aws:SourceAccount": account},
            "ArnLike": {"aws:SourceArn": f"arn:aws:bedrock-agentcore:{REGION}:{account}:*"}}}]}
    try:
        arn = iam.get_role(RoleName=name)["Role"]["Arn"]
    except iam.exceptions.NoSuchEntityException:
        arn = iam.create_role(RoleName=name, AssumeRolePolicyDocument=json.dumps(trust))["Role"]["Arn"]
    policy = {"Version": "2012-10-17", "Statement": [
        {"Effect": "Allow", "Action": "s3:GetObject", "Resource": f"arn:aws:s3:::{bucket}/{key}"},
        {"Effect": "Allow", "Action": "bedrock-agentcore:InvokeGateway",
         "Resource": f"arn:aws:bedrock-agentcore:{REGION}:{account}:gateway/{gateway_id}"},
        {"Effect": "Allow", "Action": ["bedrock-agentcore:ListEvents", "bedrock-agentcore:CreateEvent"],
         "Resource": f"arn:aws:bedrock-agentcore:{REGION}:{account}:memory/{memory_id}"},
        {"Effect": "Allow", "Action": ["logs:CreateLogGroup", "logs:DescribeLogGroups",
                                       "logs:DescribeLogStreams", "logs:CreateLogStream", "logs:PutLogEvents"],
         "Resource": f"arn:aws:logs:{REGION}:{account}:log-group:/aws/bedrock-agentcore/runtimes/*"},
    ]}
    iam.put_role_policy(RoleName=name, PolicyName="QuotationRuntimeAccess", PolicyDocument=json.dumps(policy))
    return arn


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("package", type=Path, help="runtime-package.zip")
    args = parser.parse_args()
    if not args.package.is_file():
        raise SystemExit(f"Missing package: {args.package}")
    config = config_from_file(ROOT / ".env.aws.example")
    if config["AWS_REGION"] != REGION:
        raise SystemExit("Provisioned region and deployment region differ")
    account = boto3.client("sts", region_name=REGION).get_caller_identity()["Account"]
    control = boto3.client("bedrock-agentcore-control", region_name=REGION)
    gateway_id = next(g["gatewayId"] for g in control.list_gateways()["items"]
                      if control.get_gateway(gatewayIdentifier=g["gatewayId"])["gatewayUrl"] == config["AGENTCORE_GATEWAY_URL"])
    memory_id = config["AGENTCORE_MEMORY_ID"]
    bucket = f"axrail-quotation-agentcore-{account}-{REGION}"
    key = "runtime-package.zip"
    s3 = boto3.client("s3", region_name=REGION)
    ensure_bucket(s3, bucket)
    s3.upload_file(str(args.package), bucket, key, ExtraArgs={"ServerSideEncryption": "AES256"})
    iam = boto3.client("iam")
    role_arn = ensure_role(iam, "axrail-quotation-runtime-role", account, bucket, key, gateway_id, memory_id)
    time.sleep(10)
    name = "axrailQuotationAgent"
    existing = next((a for a in control.list_agent_runtimes()["agentRuntimes"]
                     if a["agentRuntimeName"] == name), None)
    if existing:
        runtime_id = existing["agentRuntimeId"]
        control.update_agent_runtime(
            agentRuntimeId=runtime_id,
            agentRuntimeArtifact={"codeConfiguration": {
                "code": {"s3": {"bucket": bucket, "prefix": key}},
                "runtime": "PYTHON_3_13", "entryPoint": ["agent_runtime.py"]}},
            roleArn=role_arn,
            networkConfiguration={"networkMode": "PUBLIC"},
            protocolConfiguration={"serverProtocol": "HTTP"},
            lifecycleConfiguration={"idleRuntimeSessionTimeout": 300, "maxLifetime": 1800},
            environmentVariables=config,
            description="Review-first CNC quotation agent for Axrail take-home")
    else:
        response = control.create_agent_runtime(
            agentRuntimeName=name,
            agentRuntimeArtifact={"codeConfiguration": {
                "code": {"s3": {"bucket": bucket, "prefix": key}},
                "runtime": "PYTHON_3_13", "entryPoint": ["agent_runtime.py"]}},
            roleArn=role_arn,
            networkConfiguration={"networkMode": "PUBLIC"},
            protocolConfiguration={"serverProtocol": "HTTP"},
            lifecycleConfiguration={"idleRuntimeSessionTimeout": 300, "maxLifetime": 1800},
            environmentVariables=config,
            description="Review-first CNC quotation agent for Axrail take-home")
        runtime_id = response["agentRuntimeId"]
    for _ in range(60):
        runtime = control.get_agent_runtime(agentRuntimeId=runtime_id)
        if runtime["status"] == "READY":
            print(json.dumps({"region": REGION, "runtime_arn": runtime["agentRuntimeArn"],
                              "status": runtime["status"], "bucket": bucket}, indent=2))
            return
        if runtime["status"] in ("CREATE_FAILED", "UPDATE_FAILED", "DELETE_FAILED"):
            raise RuntimeError(f"Runtime failed: {runtime.get('failureReason')}")
        time.sleep(5)
    raise TimeoutError("Runtime did not become READY within five minutes")


if __name__ == "__main__":
    main()
